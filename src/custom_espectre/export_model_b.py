"""Export Stage-B model weights as a C header for on-device inference.

The Stage-B LogisticRegression classifier (walking vs running) is
a simple matrix multiply + sigmoid, so it can be baked into the
firmware as a C array.  This script reads the trained pickle and
writes ``model_b_weights.h`` which the Arduino sketch includes.

The scaler parameters (mean and scale) are also exported so the
firmware can standardise its 13-feature vector before inference.

Usage::

    python -m custom_espectre.export_model_b \\
        --model models/activity_model.pkl \\
        --out firmware/esp_inference/model_b_weights.h
"""

from __future__ import annotations

import argparse
import pickle
from pathlib import Path
from datetime import datetime

import numpy as np


FEATURE_COUNT = 13   # Stage-B has 13 features


def export_header(bundle: dict, out_path: Path) -> None:
    """Write a C header with Stage-B weights, bias, and scaler."""
    clf = bundle["clf"]
    scaler = bundle["scaler"]
    labels = bundle["labels"]

    # LogisticRegression binary: coef_ shape (1, n_features), intercept_ shape (1,)
    coef = clf.coef_.flatten().astype(np.float64)
    intercept = float(clf.intercept_[0])
    scaler_mean = scaler.mean_.astype(np.float64)
    scaler_scale = scaler.scale_.astype(np.float64)

    assert len(coef) == FEATURE_COUNT, (
        f"Expected {FEATURE_COUNT} features, got {len(coef)}"
    )

    guard = "MODEL_B_WEIGHTS_H"
    ts = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")

    lines: list[str] = [
        f"/* Auto-generated by export_model_b.py — {ts} */",
        f"/* Stage-B labels: {labels} */",
        f"/* Label index 0 = {labels[0]}, index 1 = {labels[1]} */",
        "",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        f"#define MODEL_B_FEATURE_COUNT {FEATURE_COUNT}",
        f"#define MODEL_B_LABEL_0 \"{labels[0]}\"",
        f"#define MODEL_B_LABEL_1 \"{labels[1]}\"",
        "",
        "/* Logistic regression coefficients (one per feature). */",
        "static const float kModelBCoef[MODEL_B_FEATURE_COUNT] = {",
    ]
    coef_strs = [f"    {v:.8f}f" for v in coef]
    lines.append(",\n".join(coef_strs))
    lines += [
        "};",
        "",
        f"/* Logistic regression intercept (bias). */",
        f"static const float kModelBIntercept = {intercept:.8f}f;",
        "",
        "/* StandardScaler mean — subtract from raw feature vector. */",
        "static const float kModelBScalerMean[MODEL_B_FEATURE_COUNT] = {",
    ]
    mean_strs = [f"    {v:.8f}f" for v in scaler_mean]
    lines.append(",\n".join(mean_strs))
    lines += [
        "};",
        "",
        "/* StandardScaler scale — divide after subtracting mean. */",
        "static const float kModelBScalerScale[MODEL_B_FEATURE_COUNT] = {",
    ]
    scale_strs = [f"    {v:.8f}f" for v in scaler_scale]
    lines.append(",\n".join(scale_strs))
    lines += [
        "};",
        "",
        "/* Inline helper: apply scaler then logistic classifier.",
        "   features[] must have MODEL_B_FEATURE_COUNT elements.",
        "   Returns 0 for label[0], 1 for label[1]. */",
        "static inline int model_b_predict(const float features[]) {",
        "    float z = kModelBIntercept;",
        "    for (int i = 0; i < MODEL_B_FEATURE_COUNT; ++i) {",
        "        float x = (features[i] - kModelBScalerMean[i]) / kModelBScalerScale[i];",
        "        z += kModelBCoef[i] * x;",
        "    }",
        "    /* sigmoid(z) >= 0.5  <=>  z >= 0 */",
        "    return (z >= 0.0f) ? 1 : 0;",
        "}",
        "",
        f"#endif /* {guard} */",
        "",
    ]

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Export Stage-B model weights as a C header for on-device inference"
    )
    parser.add_argument(
        "--model",
        type=Path,
        default=Path("models/activity_model.pkl"),
        help="Trained Stage-B pickle (from train_activity.py)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("firmware/esp_inference/model_b_weights.h"),
        help="Destination C header path",
    )
    return parser


def main(argv=None) -> None:
    args = build_parser().parse_args(argv)

    print("=" * 60)
    print("STAGE-B MODEL EXPORT")
    print("=" * 60)
    print(f"Loading model : {args.model}")

    with open(args.model, "rb") as fh:
        bundle = pickle.load(fh)

    export_header(bundle, args.out)

    print(f"Header written: {args.out}")
    print()
    print("Include model_b_weights.h in your Arduino sketch.")
    print("Call model_b_predict(features) after feature extraction.")


if __name__ == "__main__":
    main()
